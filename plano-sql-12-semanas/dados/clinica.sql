-- Banco CLINICA: semanas 7 a 9
-- Datas em TIMESTAMPTZ, gravadas em UTC.

DROP TABLE IF EXISTS pagamentos, consultas, pacientes, profissionais CASCADE;

CREATE TABLE profissionais (
    id SERIAL PRIMARY KEY,
    nome TEXT NOT NULL,
    especialidade TEXT NOT NULL,
    valor_consulta_centavos INTEGER NOT NULL CHECK (valor_consulta_centavos > 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pacientes (
    id SERIAL PRIMARY KEY,
    profissional_id INTEGER NOT NULL REFERENCES profissionais(id),
    nome TEXT NOT NULL,
    data_nascimento DATE NOT NULL,
    cidade TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL
);

CREATE TABLE consultas (
    id SERIAL PRIMARY KEY,
    profissional_id INTEGER NOT NULL REFERENCES profissionais(id),
    paciente_id INTEGER NOT NULL REFERENCES pacientes(id),
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    situacao TEXT NOT NULL CHECK (situacao IN ('agendada', 'realizada', 'faltou', 'cancelada')),
    cancelada_em TIMESTAMPTZ,
    CHECK (fim > inicio)
);

CREATE TABLE pagamentos (
    id SERIAL PRIMARY KEY,
    consulta_id INTEGER NOT NULL REFERENCES consultas(id),
    valor_centavos INTEGER NOT NULL CHECK (valor_centavos > 0),
    forma TEXT NOT NULL CHECK (forma IN ('pix', 'cartao', 'dinheiro')),
    pago_em TIMESTAMPTZ NOT NULL
);

