DROP TABLE IF EXISTS vendas, alocacoes, projetos, historico_salarios, funcionarios, departamentos CASCADE;

CREATE TABLE departamentos (
    id SERIAL PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    orcamento_anual_centavos BIGINT NOT NULL
);

CREATE TABLE funcionarios (
    id SERIAL PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    departamento_id INTEGER NOT NULL REFERENCES departamentos(id),
    gerente_id INTEGER REFERENCES funcionarios(id),
    cargo TEXT NOT NULL,
    salario_centavos INTEGER NOT NULL CHECK (salario_centavos > 0),
    admitido_em DATE NOT NULL,
    desligado_em DATE
);

CREATE TABLE historico_salarios (
    id SERIAL PRIMARY KEY,
    funcionario_id INTEGER NOT NULL REFERENCES funcionarios(id),
    salario_centavos INTEGER NOT NULL,
    vigente_desde DATE NOT NULL
);

CREATE TABLE projetos (
    id SERIAL PRIMARY KEY,
    nome TEXT NOT NULL,
    departamento_id INTEGER NOT NULL REFERENCES departamentos(id),
    inicio DATE NOT NULL,
    fim_previsto DATE NOT NULL,
    concluido_em DATE
);

CREATE TABLE alocacoes (
    funcionario_id INTEGER NOT NULL REFERENCES funcionarios(id),
    projeto_id INTEGER NOT NULL REFERENCES projetos(id),
    horas_semana INTEGER NOT NULL CHECK (horas_semana BETWEEN 1 AND 40),
    PRIMARY KEY (funcionario_id, projeto_id)
);

CREATE TABLE vendas (
    id SERIAL PRIMARY KEY,
    vendedor_id INTEGER NOT NULL REFERENCES funcionarios(id),
    cliente TEXT NOT NULL,
    valor_centavos INTEGER NOT NULL CHECK (valor_centavos > 0),
    vendido_em DATE NOT NULL
);

